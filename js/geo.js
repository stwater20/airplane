// 地理資料：經緯度 ↔ 世界座標（公尺），海岸線、機場、航路點
// 世界座標：x = 東，z = -北，y = 高度

export const LAT0 = 30.0;
export const LON0 = 130.0;
const M_PER_DEG_LAT = 110540;
const M_PER_DEG_LON = 111320 * Math.cos(LAT0 * Math.PI / 180);

export function toWorld(lon, lat) {
  return { x: (lon - LON0) * M_PER_DEG_LON, z: -(lat - LAT0) * M_PER_DEG_LAT };
}
export function toLonLat(x, z) {
  return { lon: x / M_PER_DEG_LON + LON0, lat: -z / M_PER_DEG_LAT + LAT0 };
}

